// Assert that every commit on a branch is a VERIFIED commit (#690 part 3, second half).
//
// ── Why the YAML ratchet is not enough ───────────────────────────────────────
// workflow-commit-ratchet.test.mjs greps workflow files for an executable
// `git commit`/`git push`. That catches a lane that inlines its git write, which
// registry-refresh.yml does. It cannot see a git write that lives inside a
// `uses:` action, because the write is not in the YAML at all.
//
// That gap is not hypothetical. Measured in bdelanghe/bdelanghe on 2026-08-23:
// no workflow there contains any executable git write and the ratchet runs clean
// (23 tests, 0 failures), yet three commits on main report
// `verified: false, reason: unsigned` — written by a third-party action invoked
// from readme.yml. A green ratchet, and unsigned commits landing daily.
//
// This check closes the class by asserting the OUTCOME rather than the mechanism:
// whatever wrote the commit, by whatever route, GitHub either verified it or did
// not. Signed-by-API and signed-by-key both pass; runner-made `git commit` does
// not, and neither does an action that does it on the lane's behalf.
//
// ── Failing closed, which is the whole point ─────────────────────────────────
// This file exists because of #688, where `gh()` returned null on ANY nonzero
// exit and the caller read every one of them as "manifest absent". A check that
// reads its own transport failure as "nothing to report" is worse than no check:
// it is a green light generated by the absence of information.
//
// So: every non-2xx THROWS. A missing token THROWS. An empty result set THROWS.
// A truncated scan THROWS. There is no path through this module that reports
// success from a failed or incomplete read.

const API = process.env.GITHUB_API_URL || "https://api.github.com";

// Hard ceiling on pagination. Hitting it is an ERROR, not a quiet stop — a cap
// that silently truncates turns "every commit is verified" into "the first N
// were", reported identically.
const MAX_PAGES = 50;
const PER_PAGE = 100;

/**
 * Pure core. Takes already-fetched commit objects; does no I/O.
 * Returns the commits that are not verified, in the order given.
 */
export function findUnverified(commits, { allow = [] } = {}) {
  const allowed = new Set(allow);
  return commits
    .filter((c) => !allowed.has(c.sha))
    .filter((c) => c?.commit?.verification?.verified !== true)
    .map((c) => ({
      sha: c.sha,
      reason: c?.commit?.verification?.reason ?? "no verification block",
      author: c?.commit?.author?.name ?? "(unknown)",
      subject: (c?.commit?.message ?? "").split("\n")[0].slice(0, 72),
    }));
}

/**
 * Guards against an allowlist that outlives the commits it excuses. A SHA that
 * is no longer in the scanned range is dead weight that quietly widens the
 * exemption if history is ever rewritten onto it.
 */
export function findStaleAllowEntries(commits, allow = []) {
  const present = new Set(commits.map((c) => c.sha));
  return allow.filter((sha) => !present.has(sha));
}

async function ghJson(url, token) {
  const res = await fetch(url, {
    headers: {
      authorization: `Bearer ${token}`,
      accept: "application/vnd.github+json",
      "x-github-api-version": "2022-11-28",
    },
  });

  // The #688 discrimination. 404 is the ONLY status that means "not there", and
  // even that is fatal here: a branch we were told to audit must exist.
  if (!res.ok) {
    const body = await res.text().catch(() => "");
    throw new Error(
      `GitHub API ${res.status} ${res.statusText} for ${url}\n` +
        `${body.slice(0, 400)}\n` +
        `Refusing to report on an incomplete read. A transport failure is not ` +
        `an absence of unverified commits (#688).`,
    );
  }
  return res.json();
}

export async function fetchCommits({ owner, repo, ref, since, token }) {
  if (!token) {
    throw new Error(
      "No token supplied. This check cannot run unauthenticated — refusing to " +
        "skip, because a skipped verification check reports the same green as a " +
        "passing one.",
    );
  }

  const commits = [];
  for (let page = 1; page <= MAX_PAGES; page++) {
    const u = new URL(`${API}/repos/${owner}/${repo}/commits`);
    u.searchParams.set("sha", ref);
    u.searchParams.set("per_page", String(PER_PAGE));
    u.searchParams.set("page", String(page));
    if (since) u.searchParams.set("since", since);

    const batch = await ghJson(u.toString(), token);
    commits.push(...batch);
    if (batch.length < PER_PAGE) return commits;
  }

  throw new Error(
    `Pagination hit MAX_PAGES=${MAX_PAGES} (${commits.length} commits) without ` +
      `reaching the end of ${ref}. Set a 'since' boundary and state it, or raise ` +
      `the cap deliberately. Reporting on a truncated scan would be a silent cap.`,
  );
}

export function formatReport({ owner, repo, ref, since, commits, offenders }) {
  const bound = since ? `since ${since}` : "full history of the ref";
  const lines = [
    `Scanned ${commits.length} commit(s) on ${owner}/${repo}@${ref} (${bound}).`,
  ];
  if (offenders.length) {
    lines.push(`${offenders.length} unverified:`);
    for (const o of offenders) {
      lines.push(`  ${o.sha.slice(0, 7)}  ${o.reason.padEnd(20)} ${o.author} — ${o.subject}`);
    }
  }
  return lines.join("\n");
}

/**
 * The denominator guard. `findUnverified([])` returns `[]` — an empty scan looks
 * exactly like a clean one, which is the failure `registry/scope.ts` exists to
 * prevent ("we measured all 45" quietly becoming "we measured some of them").
 * Callers must run this first; it is exported rather than inlined so it can be
 * tested and so no caller can forget it silently.
 */
export function assertScanned(commits, { ref } = {}) {
  if (!Array.isArray(commits) || commits.length === 0) {
    throw new Error(
      `Scanned 0 commits on ${ref ?? "the ref"}. An empty scan reports the same ` +
        `green as a clean one, so it is an error. Check the ref name and the ` +
        `'since' boundary.`,
    );
  }
  return commits.length;
}
